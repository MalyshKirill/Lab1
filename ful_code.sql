DROP TABLE IF EXISTS deferments;
DROP TABLE IF EXISTS conscripts;

-- Главная таблица: Призывники (Учётные карточки)
CREATE TABLE conscripts (
    conscript_id SERIAL PRIMARY KEY,
    last_name CHARACTER VARYING(50) NOT NULL,
    first_name CHARACTER VARYING(50) NOT NULL,
    middle_name CHARACTER VARYING(50),
    birth_date DATE NOT NULL,
    address CHARACTER VARYING(150),
    phone CHARACTER VARYING(20),
    education CHARACTER VARYING(100) NOT NULL,
    marital_status CHARACTER VARYING(30) NOT NULL
);

-- Зависимая таблица: Отсрочки / Повестки (со ссылочной целостностью и каскадами)
CREATE TABLE deferments (
    deferment_id SERIAL PRIMARY KEY,
    conscript_id INTEGER NOT NULL,
    reason CHARACTER VARYING(100) NOT NULL,
    end_date DATE NOT NULL,
    FOREIGN KEY (conscript_id) REFERENCES conscripts (conscript_id)
        ON UPDATE CASCADE
        ON DELETE CASCADE
);
